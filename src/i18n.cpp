void set_language(Language lang) {
    g_language = lang;
}

const char* tr(StrId id) {
    unsigned short idx = static_cast<unsigned short>(id);
    if (idx >= static_cast<unsigned short>(StrId::STR_COUNT)) return "???";
    const char* const* table = (g_language == cn) ? table_cn : table_en;
    const char* s = table[idx];
    if (s && s[0] != '\0') return s;
    // Fallback to English for empty strings
    return table_en[idx];
}

std::string tr_f(StrId id, ...) {
    const char* fmt = tr(id);
    char buf[1024];
    va_list args;
    va_start(args, id);
    std::vsnprintf(buf, sizeof(buf), fmt, args);
    va_end(args);
    return std::string(buf);
}
